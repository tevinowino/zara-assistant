/**
 * Zara's icon vocabulary: every symbol the interface draws, under the name of what it
 * means (ChevronDown, Trash2, Sparkles), so a screen asks for a meaning and never for a
 * particular icon set. Today each is drawn from Iconoir (MIT); changing a symbol, or the
 * set, is a one-line change here.
 *
 * Every glyph is an SVG that takes the colour of the surrounding text. Give it `size` in
 * CSS pixels (24 by default) and, if the default line weight is wrong for the size,
 * `strokeWidth`.
 */
export interface GlyphProps extends Omit<SVGProps<SVGSVGElement>, "ref" | "width" | "height"> {
	/** Width and height in CSS pixels. */
	size?: number | string;
}

/** An icon component: what the vocabulary below exports and what a prop that holds an icon accepts. */
export type Glyph = ComponentType<GlyphProps>;

type IconoirIcon = ComponentType<SVGProps<SVGSVGElement>>;

const DEFAULT_SIZE_PX = 24;

function glyph(Icon: IconoirIcon, displayName: string): Glyph {
	const Sized = forwardRef<SVGSVGElement, GlyphProps>(function Sized(
		{ size = DEFAULT_SIZE_PX, ...rest },
		ref
	) {
		return <Icon ref={ref} width={size} height={size} {...rest} />;
	});
	Sized.displayName = displayName;
	return Sized;
}

