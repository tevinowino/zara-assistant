import React from "react";
import ReactMarkdown, { type Components } from "react-markdown";
import remarkGfm from "remark-gfm";
import remarkMath from "remark-math";
import rehypeKatex from "rehype-katex";
import rehypeRaw from "rehype-raw";
import rehypeSanitize from "rehype-sanitize";
import { openUrl } from "@tauri-apps/plugin-opener";
import "katex/dist/katex.min.css";
import { zaraSanitizeSchema } from "./sanitizeSchema";
import { isSafeExternalUrl } from "./safeLinks";
import { ChatCodeBlock } from "./ChatCodeBlock";

// react-markdown v9 dropped the `inline` prop on `code`: block code is only
// distinguishable by its parent being `pre`. So `pre` is overridden (it only
// ever wraps block code) and reads the language from its single child <code>;
// `code` is left to handle genuinely inline spans.
const MarkdownPre: Components["pre"] = ({ children }) => {
	const codeElement = Array.isArray(children) ? children[0] : children;
	if (!React.isValidElement(codeElement)) {
		return <pre>{children}</pre>;
	}
	const codeProps = codeElement.props as { className?: string; children?: React.ReactNode };
	return <ChatCodeBlock className={codeProps.className}>{codeProps.children}</ChatCodeBlock>;
};

const MarkdownInlineCode: Components["code"] = ({ children }) => (
	<code className="zai-inline-code">{children}</code>
);

// The notch has no navigation chrome to recover from an accidental in-app
// navigation, so a link never navigates: it opens in the system browser, and only
// if it is an http(s) or mailto link.
const MarkdownLink: Components["a"] = ({ href, children }) => (
	<a
		href={undefined}
		role="link"
		tabIndex={0}
		onClick={(event) => {
			event.preventDefault();
			if (isSafeExternalUrl(href)) void openUrl(href);
		}}
		onKeyDown={(event) => {
			if (event.key === "Enter" && isSafeExternalUrl(href)) void openUrl(href);
		}}
		className="zai-link"
	>
		{children}
	</a>
);

// A wide table's minimum width would otherwise push the whole panel wider.
const MarkdownTable: Components["table"] = ({ children }) => (
	<div className="zai-table-scroll">
		<table>{children}</table>
	</div>
);

const MARKDOWN_COMPONENTS: Components = {
	pre: MarkdownPre,
	code: MarkdownInlineCode,
	a: MarkdownLink,
	table: MarkdownTable
};

interface ChatMarkdownProps {
	text: string;
}

export function ChatMarkdown({ text }: ChatMarkdownProps) {
	return (
		<div className="zai-md">
			<ReactMarkdown
				remarkPlugins={[remarkGfm, remarkMath]}
				// Order matters. rehypeSanitize must run after rehypeRaw (otherwise raw
				// HTML would land after sanitising and the allowlist would do nothing)
				// and before rehypeKatex (KaTeX's own output is generated by our code
				// from plain text, not by the model, so it is trusted).
				rehypePlugins={[rehypeRaw, [rehypeSanitize, zaraSanitizeSchema], rehypeKatex]}
				components={MARKDOWN_COMPONENTS}
			>
				{text}
			</ReactMarkdown>
		</div>
	);
}
