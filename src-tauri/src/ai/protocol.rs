//! The text protocol between Zara and the model.
//!
//! The model cannot call functions here, so it asks for extra context or
//! reports side effects by emitting plain-text tags inside its reply:
//!
//! - `[[SEE_SCREEN]]` / `[[SEE_NOTES]]`: a reply that is *only* this token asks
//!   for the screen or the notes list. A token buried in prose is stripped and
//!   never triggers anything, so a model that merely mentions its own abilities
//!   cannot cause a screenshot.
//! - `[[REMEMBER: fact]]`, `[[NOTE_ADD: text]]`, `[[NOTE_EDIT:n: text]]`,
//!   `[[NOTE_DELETE:n]]`: inline side effects, always stripped from what the
//!   user sees.
//!
//! This is a faithful port of Electron Zara's `electron/protocol/*`. The
//! functions are pure; `protocol_cases.json` (generated by running the original
//! TypeScript) pins them to identical behaviour.

